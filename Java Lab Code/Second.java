public class Second {
    public static void main(String[] args) {
        int a=10;
        float b=20.5f;
        double c=30.99;
        char d='A';

        System.out.println("Integer value: " + a);
        System.out.println("Float value: " + b);
        System.out.println("Double value: " + c);
        System.out.println("Character value: " + d);
    }
}
